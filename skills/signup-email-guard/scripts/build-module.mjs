#!/usr/bin/env node
// Writes the domain lists as one ES module a service vendors (commits) and imports on the server only.
// node scripts/build-module.mjs <service>/src/email-domain-blocklist.js
//
// The module exports space-separated strings (cheaper to parse than a 10k-element array literal) plus the
// source facts; the service turns them into Sets and owns the matching rules (see SKILL.md).
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const out = process.argv[2];
if (!out) { console.error('usage: node scripts/build-module.mjs <output.js>'); process.exit(2); }
const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const curated = JSON.parse(read('data/alias-domains.json'));
const source = JSON.parse(read('data/disposable-source.json'));
const { NEVER_BLOCK } = await import(new URL('scripts/never-block.mjs', root));

const valid = domain => /^[a-z0-9-]+(\.[a-z0-9-]+)+$/.test(domain);
const group = name => [...new Set(curated.domains.filter(entry => entry.group === name).map(entry => entry.domain))].sort();
const relay = group('relay'), apple = group('apple'), curatedSet = new Set([...relay, ...apple]);
const disposable = read('data/disposable-domains.txt').split('\n').filter(Boolean).filter(domain => !curatedSet.has(domain));
const all = [...relay, ...apple, ...disposable];
const bad = all.filter(domain => !valid(domain)), blocked = NEVER_BLOCK.filter(domain => all.includes(domain));
if (bad.length || blocked.length) throw new Error(`refusing to build: invalid ${bad.slice(0, 5)} / mainstream ${blocked}`);

const chunks = [];
for (let i = 0; i < disposable.length; i += 60) chunks.push(`'${disposable.slice(i, i + 60).join(' ')}'`);
const text = `// Generated by ~/.agents/skills/signup-email-guard/scripts/build-module.mjs; never edit by hand.
// Sign-up email domains to refuse, by group: relay ${relay.length} (anonymous forwarding services, checked ${curated.checkedAt}),
// apple ${apple.length} (Hide My Email), disposable ${disposable.length} (${source.repo} @ ${source.commit.slice(0, 12)},
// ${source.license}, fetched ${source.fetchedAt}). Refresh: node scripts/refresh.mjs, then build again.
export const EMAIL_DOMAIN_SOURCE = Object.freeze({checkedAt: '${curated.checkedAt}', disposableCommit: '${source.commit}', disposableFetchedAt: '${source.fetchedAt}'});
export const RELAY_DOMAINS = '${relay.join(' ')}';
export const APPLE_DOMAINS = '${apple.join(' ')}';
export const DISPOSABLE_DOMAINS = [
${chunks.join(',\n')},
].join(' ');
`;
writeFileSync(resolve(out), text);
console.log(`${resolve(out)}: relay ${relay.length}, apple ${apple.length}, disposable ${disposable.length}, ${Buffer.byteLength(text)} bytes`);
